CREATE EXTENSION IF NOT EXISTS pgcrypto;  

DROP TABLE IF EXISTS status_history, requests, document_types, users, programs CASCADE;

CREATE TABLE programs (
    program_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL UNIQUE,
    school       VARCHAR(100) NOT NULL
);

CREATE TABLE users (
    user_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(120) NOT NULL UNIQUE,
    password_hash  TEXT         NOT NULL,                       
    full_name      VARCHAR(100) NOT NULL,
    role           VARCHAR(10)  NOT NULL CHECK (role IN ('student', 'staff')),
    program_id     INTEGER REFERENCES programs(program_id) ON DELETE RESTRICT,
    created_at     TIMESTAMP    NOT NULL DEFAULT now(),
    CHECK (email LIKE '%@astanait.edu.kz'),                     
    CHECK (role = 'staff' OR program_id IS NOT NULL)             
);

CREATE TABLE document_types (
    type_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100) NOT NULL UNIQUE,
    processing_days  SMALLINT     NOT NULL CHECK (processing_days BETWEEN 1 AND 30)
);

CREATE TABLE requests (
    request_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id   INTEGER      NOT NULL REFERENCES users(user_id)          ON DELETE RESTRICT,
    type_id      INTEGER      NOT NULL REFERENCES document_types(type_id) ON DELETE RESTRICT,
    handled_by   INTEGER      REFERENCES users(user_id)                   ON DELETE SET NULL,
    status       VARCHAR(12)  NOT NULL DEFAULT 'New'
                 CHECK (status IN ('New', 'In progress', 'Ready', 'Cancelled')),
    purpose      VARCHAR(200) NOT NULL,
    copies       SMALLINT     NOT NULL DEFAULT 1 CHECK (copies BETWEEN 1 AND 10),
    created_at   TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at   TIMESTAMP    NOT NULL DEFAULT now(),
    CHECK (updated_at >= created_at)
);

CREATE TABLE status_history (
    history_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  INTEGER     NOT NULL REFERENCES requests(request_id) ON DELETE CASCADE,
    old_status  VARCHAR(12) CHECK (old_status IN ('New', 'In progress', 'Ready', 'Cancelled')),
    new_status  VARCHAR(12) NOT NULL CHECK (new_status IN ('New', 'In progress', 'Ready', 'Cancelled')),
    changed_by  INTEGER     NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    changed_at  TIMESTAMP   NOT NULL DEFAULT now(),
    CHECK (old_status IS DISTINCT FROM new_status)
);

CREATE INDEX idx_requests_student ON requests(student_id);
CREATE INDEX idx_requests_status  ON requests(status);
CREATE INDEX idx_history_request  ON status_history(request_id);
