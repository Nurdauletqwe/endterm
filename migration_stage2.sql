CREATE TABLE IF NOT EXISTS pickup_points (
    point_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block     VARCHAR(4)  NOT NULL CHECK (block IN ('C1.1', 'C1.2', 'C1.3')),
    room      VARCHAR(10) NOT NULL,
    UNIQUE (block, room)
);
ALTER TABLE requests ADD COLUMN IF NOT EXISTS pickup_point_id INTEGER
    REFERENCES pickup_points(point_id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_requests_pickup ON requests(pickup_point_id);

