UPDATE requests r
   SET pickup_point_id = (SELECT point_id FROM pickup_points ORDER BY point_id OFFSET (r.request_id % 9) LIMIT 1)
 WHERE r.status = 'Ready' AND r.pickup_point_id IS NULL;
