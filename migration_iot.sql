CREATE TABLE IF NOT EXISTS lockers (
    locker_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_id   INTEGER NOT NULL UNIQUE REFERENCES pickup_points(point_id) ON DELETE RESTRICT,
    label      VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS locker_events (
    event_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    locker_id    INTEGER     NOT NULL REFERENCES lockers(locker_id) ON DELETE CASCADE,
    request_id   INTEGER     REFERENCES requests(request_id) ON DELETE SET NULL,  
    event_type   VARCHAR(20) NOT NULL CHECK (event_type IN ('heartbeat', 'door_closed', 'door_opened', 'document_present', 'document_removed')),
    battery_pct  SMALLINT    CHECK (battery_pct BETWEEN 0 AND 100),
    created_at   TIMESTAMP   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_locker_events_locker_time ON locker_events(locker_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_locker_events_request     ON locker_events(request_id);

INSERT INTO lockers (point_id, label)
SELECT p.point_id, 'LOCKER-' || p.block || '-' || p.room
FROM pickup_points p
ON CONFLICT DO NOTHING;
